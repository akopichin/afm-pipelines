test('plan approval displays the bound spec delta and rejects tampering', async t => {
  const {session, root, save} = fixture(t);
  save({schema_version:1, revision:1, title:'Helper', views:[], skip_reason:'Local lifecycle change'});
  const delta = '# Validation before publication\n\n## ADDED\n';
  const deltaFile = path.join(session, 'delta.md');
  fs.writeFileSync(deltaFile, delta);
  const deltaHash = createHash('sha256').update(delta).digest('hex');
  fs.writeFileSync(path.join(session, 'project.json'), JSON.stringify({spec:{delta_sha256:deltaHash}}));
  await renderPlan(session, root);
  const approval = fs.readFileSync(path.join(session, 'c4-approval.md'), 'utf8');
  assert(approval.includes(delta.trim()));
  const question = path.join(session, 'q1.question.json');
  fs.writeFileSync(question, JSON.stringify({id:'q1', question:'Local lifecycle change'}));
  assert.throws(() => bindQuestion(session, question), /does not contain/);
  fs.writeFileSync(question, JSON.stringify({id:'q1', question:approval}));
  bindQuestion(session, question);
  verifyC4(session);
  fs.appendFileSync(deltaFile, 'Unauthorized change\n');
  assert.throws(() => verifyC4(session), /Spec delta differs/);
});
