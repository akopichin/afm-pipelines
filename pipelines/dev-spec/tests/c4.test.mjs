const example = () => JSON.parse(fs.readFileSync(fileURLToPath(new URL('../planning/c4-example.json',import.meta.url))));
function fixture(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'c4-plan-'))), session = path.join(root,'run','plan');
  t.after(() => fs.rmSync(root,{recursive:true,force:true}));
  fs.mkdirSync(session,{recursive:true}); execFileSync('git',['init','-q',root]);
  fs.writeFileSync(path.join(root,'source.ts'),'export function createOrder() {}\n');
  fs.writeFileSync(path.join(session,'dev-plan.md'),'# Plan\n\nT1 and T2\n');
  fs.writeFileSync(path.join(session,'project.json'),'{}\n');
  const save = model => fs.writeFileSync(path.join(session,'c4.json'),JSON.stringify(model,null,2)+'\n');
  return {root,session,save};
}
test('C4 validates real abstraction boundaries, directed relations and plan/source references', () => {
  validateModel(example());
  const reordered = example();
  reordered.views[0].nodes[2].after = Object.fromEntries(Object.entries(reordered.views[0].nodes[2].before).reverse());
  validateModel(reordered);
  const invalid = example(); invalid.views[0].relations[0].to = 'missing';
  assert.throws(() => validateModel(invalid), /Dangling/);
  const absent = example(); absent.views[0].relations[2].before = absent.views[0].relations[2].after;
  assert.throws(() => validateModel(absent), /absent/);
  const level = example(); level.views[0].nodes[0].after.type = 'container';
  assert.throws(() => validateModel(level), /abstraction levels/);
  const ungrounded = example(); delete ungrounded.views[0].nodes[0].source_refs;
  assert.throws(() => validateModel(ungrounded), /source_refs/);
  const unplanned = example(); delete unplanned.views[0].nodes[0].task_ids;
  assert.throws(() => validateModel(unplanned), /task_ids/);
  assert.throws(() => validateModel({schema_version:1,revision:1,title:'Docs',views:[]}), /skip_reason/);
});
test('before/after share node positions, have Russian labels and escape source text', async () => {
  const model = example(), view = model.views[0], layout = await layoutView(view);
  const before = renderSvg(model,view,layout,'before'), after = renderSvg(model,view,layout,'after');
  assert.match(before,/Было/); assert.match(after,/Стало/);
  assert(!before.includes('Реестр ключей')); assert(after.includes('Реестр ключей'));
  const positions = layout.children.find(node => node.id === 'scope').children;
  const node = positions.find(node => node.id === 'service');
  const scope = layout.children.find(node => node.id === 'scope');
  for (const svg of [before,after]) assert(svg.includes(`<rect x="${node.x + scope.x}" y="${node.y + scope.y}" width="360"`));
  view.nodes[0].after.name = '<script>alert(1)</script>';
  assert(!renderSvg(model,view,layout,'after').includes('<script>'));
});
test('real PNGs work offline; approval binds source, plan, revision, every image and actual question', async t => {
  const f = fixture(t), model = example(); f.save(model);
  const frozen = freeze(path.join(f.root,'run/bootstrap'));
  execFileSync(process.execPath,[path.join(frozen,'c4.mjs'),'render','--session',f.session,'--root',f.root],{cwd:f.root});
  const manifest = JSON.parse(fs.readFileSync(path.join(f.session,'c4-manifest.json')));
  assert.equal(Object.keys(manifest.views).length,2);
  for (const name of Object.keys(manifest.files).filter(name => name.endsWith('.png'))) {
    const png = fs.readFileSync(path.join(f.session,'artifacts',name));
    assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
    assert.equal(png.readUInt32BE(16),2200);
  }
  const md = fs.readFileSync(path.join(f.session,'c4-approval.md'),'utf8');
  assert.equal((md.match(/!\[/g) || []).length,1);
  assert(md.includes('| C4')); assert(!md.includes('<details'));
  assert.equal((approvalMarkdown(model,manifest,'all').match(/!\[/g) || []).length,4);
  assert.throws(() => verifyC4(f.session), /Bind the actual/);
  const question = path.join(f.session,'autonomous_execution.q1.question.json');
  fs.writeFileSync(question,JSON.stringify({id:'q1',question:'# Approve\n\n'+md+'\nChecks: focused tests.'}));
  bindQuestion(f.session,question); verifyC4(f.session);
  const receiptFile = path.join(f.session,'c4-manifest.json'), receiptBytes = fs.readFileSync(receiptFile);
  const incomplete = JSON.parse(receiptBytes); delete incomplete.files[incomplete.views[model.primary_view].before];
  fs.writeFileSync(receiptFile,JSON.stringify(incomplete));
  assert.throws(() => verifyC4(f.session), /Missing C4 image evidence/); fs.writeFileSync(receiptFile,receiptBytes);
  const questionBytes = fs.readFileSync(question);
  fs.writeFileSync(question,JSON.stringify({id:'q1',question:'A different plan'}));
  assert.throws(() => verifyC4(f.session), /question changed/); fs.writeFileSync(question,questionBytes);
  const firstImage = path.join(f.session,'artifacts',manifest.views[model.primary_view].after), original = fs.readFileSync(firstImage);
  fs.appendFileSync(firstImage,'tampered'); assert.throws(() => verifyC4(f.session), /artifact changed/); fs.writeFileSync(firstImage,original);
  fs.appendFileSync(path.join(f.session,'dev-plan.md'),'Changed'); assert.throws(() => verifyC4(f.session), /stale/);
  model.revision++; f.save(model);
  const next = await renderPlan(f.session,f.root);
  assert.notEqual(next.views[model.primary_view].after,manifest.views[model.primary_view].after);
  assert(fs.readFileSync(firstImage).equals(original),'Earlier approval images remain unchanged');
  assert.throws(() => bindQuestion(f.session,question), /does not contain/);
  fs.writeFileSync(question,JSON.stringify({id:'q2',question:fs.readFileSync(path.join(f.session,'c4-approval.md'),'utf8')}));
  bindQuestion(f.session,question); verifyC4(f.session);
  fs.appendFileSync(path.join(f.root,'source.ts'),'// source drift\n'); assert.throws(() => verifyC4(f.session), /Source changed/);
});
test('external actors stay outside the C4 boundary and their edges connect to scoped nodes', async () => {
  const model = example(), view = model.views[0];
  const person = {name:'Покупатель',type:'person',description:'Оформляет заказ'};
  view.nodes.unshift({id:'person',external:true,before:person,after:person,source_refs:['docs/api.md:10']});
  const relation = {label:'Отправляет заказ',technology:'HTTP'};
  view.relations.unshift({id:'submit',from:'person',to:'handler',before:relation,after:relation});
  validateModel(model);
  const layout = await layoutView(view), boundary = layout.children.find(node => node.id === 'scope');
  assert(layout.children.some(node => node.id === 'person'));
  assert(!boundary.children.some(node => node.id === 'person'));
  assert.equal(layout.edges.find(edge => edge.id === 'submit').sections.length,1);
  assert(renderSvg(model,view,layout,'after').includes('Покупатель'));
});
